export function findLogoForSubscription(name) {
  if (!name) return null;
  const clean = name.toLowerCase().replace(/[^a-z0-9]/g, " ").trim();
  const tokens = clean.split(/\s+/).filter(Boolean);

  // 1. Direct keyword match
  for (const entry of LOGO_KEYWORD_MAP) {
    for (const kw of entry.keywords) {
      if (tokens.includes(kw) || clean.includes(kw)) {
        return entry.logo;
      }
    }
  }

  // 2. Preset catalog match
  const match = PRESET_SUBSCRIPTIONS.find(p => {
    const pClean = p.name.toLowerCase();
    const pDomain = p.domain.split('.')[0].toLowerCase();
    return clean.includes(pClean) || pClean.includes(clean) || tokens.includes(pDomain);
  });

  return match ? match.logo : null;
}
